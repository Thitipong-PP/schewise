CREATE SCHEMA commerce;
CREATE TABLE commerce.customers (
    tenant_id integer NOT NULL,
    id bigint GENERATED ALWAYS AS IDENTITY,
    email varchar(254) NOT NULL,
    display_name text NOT NULL,
    PRIMARY KEY (tenant_id, id),
    UNIQUE (tenant_id, email)
);
CREATE TABLE commerce.orders (
    tenant_id integer NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id bigint NOT NULL,
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','paid','cancelled')),
    subtotal numeric(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    total numeric GENERATED ALWAYS AS (subtotal * 1.07) STORED,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id,id),
    FOREIGN KEY (tenant_id,customer_id) REFERENCES commerce.customers(tenant_id,id)
        ON UPDATE RESTRICT ON DELETE CASCADE
);
CREATE INDEX orders_customer_idx ON commerce.orders(tenant_id,customer_id) INCLUDE(status);
CREATE VIEW commerce.paid_orders AS SELECT tenant_id,id,customer_id,total FROM commerce.orders WHERE status='paid';
CREATE MATERIALIZED VIEW commerce.order_summary AS SELECT tenant_id,status,count(*) AS orders FROM commerce.orders GROUP BY tenant_id,status;
CREATE TABLE commerce.events (id bigint,occurred_on date NOT NULL,event_type text) PARTITION BY RANGE(occurred_on);
