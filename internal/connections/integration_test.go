func TestRunningSyncBlocksDeletion(t *testing.T) {
	s, _, _, alice, unit, _ := fixture(t)
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = listener.Close() }()
	accepted := make(chan net.Conn, 1)
	go func() {
		conn, err := listener.Accept()
		if err == nil {
			accepted <- conn
		}
	}()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	created, err := s.Create(ctx, alice, CreateInput{Input: Input{UnitID: unit, Name: "Blocking synthetic target", Engine: "postgres", Host: "127.0.0.1", Port: listener.Addr().(*net.TCPAddr).Port, Database: "fixture", Username: "reader", SSLMode: "disable"}, Password: "synthetic"})
	if err != nil {
		t.Fatal(err)
	}
	finished := make(chan error, 1)
	go func() { _, err := s.Run(ctx, alice, created.Connection.ID, true); finished <- err }()
	var remote net.Conn
	select {
	case remote = <-accepted:
	case <-ctx.Done():
		t.Fatal("sync never connected to synthetic listener")
	}
	defer func() { _ = remote.Close() }()
	if _, err := s.Delete(ctx, alice, created.Connection.ID, &created.Connection.Name); !errors.Is(err, ErrBusy) {
		t.Fatal("real in-progress sync did not block delete", err)
	}
	_ = remote.Close()
	select {
	case err := <-finished:
		if err != nil {
			t.Fatal(err)
		}
	case <-ctx.Done():
		t.Fatal("sync did not release after target disconnected")
	}
}
