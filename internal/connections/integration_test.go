func metadataDB(t *testing.T) *sql.DB {
	t.Helper()
	dsn := os.Getenv("SCHEWISE_TEST_DATABASE_URL")
	if dsn == "" {
		if os.Getenv("SCHEWISE_INTEGRATION_TESTS") != "1" {
			t.Skip("run make integration-test")
		}
		cfg, err := config.Load()
		if err != nil {
			t.Fatal(err)
		}
		dsn = cfg.DatabaseURL
	}
	ctx := context.Background()
	admin, err := database.Open(ctx, dsn)
	if err != nil {
		t.Fatal("test metadata database unavailable")
	}
	schema := "connections_test_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	if _, err := admin.Exec(`CREATE SCHEMA ` + schema); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_, err := admin.Exec(`DROP SCHEMA ` + schema + ` CASCADE`)
		if err != nil {
			t.Error(err)
		}
		_ = admin.Close()
	})
	parsed, err := url.Parse(dsn)
	if err != nil {
		t.Fatal(err)
	}
	q := parsed.Query()
	q.Set("search_path", schema)
	parsed.RawQuery = q.Encode()
	db, err := database.Open(ctx, parsed.String())
	if err != nil {
		t.Fatal("isolated metadata connection failed")
	}
	t.Cleanup(func() { _ = db.Close() })
	if err := database.Migrate(ctx, db); err != nil {
		t.Fatal(err)
	}
	return db
}
func targetDB(t *testing.T) (Input, string, *pgx.Conn) {
	t.Helper()
	dsn := os.Getenv("SCHEWISE_TEST_TARGET_ADMIN_URL")
	if dsn == "" {
		dsn = os.Getenv("SCHEWISE_TEST_DATABASE_URL")
	}
	if dsn == "" {
		t.Fatal("set SCHEWISE_TEST_TARGET_ADMIN_URL for a separate synthetic PostgreSQL target")
	}
	ctx := context.Background()
	admin, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatal("synthetic target server unavailable")
	}
	name := "schewise_target_test_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	if _, err := admin.Exec(ctx, `CREATE DATABASE `+name); err != nil {
		_ = admin.Close(ctx)
		t.Fatal("target tests require CREATEDB on the dedicated test server")
	}
	t.Cleanup(func() {
		_, err := admin.Exec(context.Background(), `DROP DATABASE `+name+` WITH (FORCE)`)
		if err != nil {
			t.Error(err)
		}
		_ = admin.Close(context.Background())
	})
	cfg := admin.Config()
	cfg.Database = name
	target, err := pgx.ConnectConfig(ctx, cfg)
	if err != nil {
		t.Fatal("isolated target connection failed")
	}
	t.Cleanup(func() { _ = target.Close(context.Background()) })
	if _, err := target.Exec(ctx, `CREATE SCHEMA shop;
 CREATE TABLE shop.customers(tenant_id integer NOT NULL,id bigint GENERATED ALWAYS AS IDENTITY,email varchar(120) NOT NULL,PRIMARY KEY(tenant_id,id),UNIQUE(tenant_id,email));
 CREATE TABLE shop.orders(tenant_id integer NOT NULL,id bigint GENERATED BY DEFAULT AS IDENTITY,customer_id bigint NOT NULL,amount numeric(12,2) DEFAULT 0 CHECK(amount>=0),total numeric GENERATED ALWAYS AS (amount*2) STORED,PRIMARY KEY(tenant_id,id),FOREIGN KEY(tenant_id,customer_id) REFERENCES shop.customers(tenant_id,id) ON DELETE CASCADE ON UPDATE RESTRICT);
 CREATE INDEX orders_amount_idx ON shop.orders(amount DESC) INCLUDE(customer_id) WHERE amount>0;
 CREATE VIEW shop.order_totals AS SELECT tenant_id,total FROM shop.orders;
 CREATE MATERIALIZED VIEW shop.order_summary AS SELECT tenant_id,count(*) AS orders FROM shop.orders GROUP BY tenant_id;
 CREATE TABLE shop.events(id integer,occurred date) PARTITION BY RANGE(occurred);
 COMMENT ON SCHEMA shop IS 'Synthetic shop';COMMENT ON TABLE shop.orders IS 'Synthetic orders';COMMENT ON COLUMN shop.orders.amount IS 'Before tax';`); err != nil {
		t.Fatal(err)
	}
	return Input{Engine: "postgres", Host: cfg.Host, Port: int(cfg.Port), Database: name, Username: cfg.User, SSLMode: "disable", Name: "Synthetic shop"}, cfg.Password, target
}
