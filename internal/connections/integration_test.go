func TestPostgresSyncStatisticsHistoryAndReadOnly(t *testing.T) {
	s, repo, db, alice, unit, logs := fixture(t)
	in, password, target := targetDB(t)
	in.UnitID = unit
	ctx := context.Background()
	created, err := s.Create(ctx, alice, CreateInput{Input: in, Password: password})
	if err != nil {
		t.Fatal(err)
	}
	id := created.Connection.ID
	// Explicit credentials and runtime settings must override ambient application settings.
	t.Setenv("PGPASSWORD", "ambient-secret-must-not-be-used")
	t.Setenv("PGOPTIONS", "-c default_transaction_read_only=off")
	t.Setenv("PGAPPNAME", "ambient-app")
	conn, err := s.policy.connect(ctx, in, password, 30*time.Second)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := conn.Exec(ctx, `CREATE TABLE public.must_not_exist(id int)`); err == nil {
		t.Fatal("target session allowed writes")
	}
	_ = conn.Close(ctx)
	first, err := s.Run(ctx, alice, id, true)
	if err != nil || !first.Success || !first.CreatedSnapshot {
		t.Fatalf("first sync: %v %s", err, first.Code)
	}
	snapshot, err := s.Snapshot(ctx, alice, id, uuid.Nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(snapshot.Content.Schemas) != 2 || snapshot.Stats.Tables != 5 {
		t.Fatalf("unexpected catalog: %+v", snapshot.Stats)
	}
	expectedKinds := map[string]string{"customers": "table", "orders": "table", "order_totals": "view", "order_summary": "materialized_view", "events": "partitioned_table"}
	for _, schema := range snapshot.Content.Schemas {
		if schema.Name != "shop" {
			continue
		}
		if schema.Comment == nil || *schema.Comment != "Synthetic shop" {
			t.Fatal("schema comment missing")
		}
		for _, table := range schema.Tables {
			if expectedKinds[table.Name] != table.Kind {
				t.Fatal("unexpected normalized object kind")
			}
			delete(expectedKinds, table.Name)
		}
	}
	if len(expectedKinds) != 0 {
		t.Fatal("normalized snapshot omitted expected relations")
	}
	var orders Table
	for _, schema := range snapshot.Content.Schemas {
		if schema.Name == "shop" {
			for _, table := range schema.Tables {
				if table.Name == "orders" {
					orders = table
				}
			}
		}
	}
	if len(orders.Columns) != 5 || orders.Columns[3].DataType != "numeric(12,2)" || orders.Columns[3].Comment == nil || orders.Columns[4].Generated != "stored" {
		t.Fatal("column facts missing")
	}
	found := false
	for _, c := range orders.Constraints {
		if c.Kind == "foreign_key" {
			found = true
			if strings.Join(c.Columns, ",") != "tenant_id,customer_id" || c.Reference == nil || strings.Join(c.Reference.Columns, ",") != "tenant_id,id" || c.OnDelete != "cascade" || c.OnUpdate != "restrict" {
				t.Fatal("composite FK not preserved")
			}
		}
	}
	if !found {
		t.Fatal("declared FK missing")
	}
	if len(orders.Indexes) != 2 {
		t.Fatal("indexes missing")
	}
	if orders.Comment == nil || *orders.Comment != "Synthetic orders" || *orders.Columns[3].Comment != "Before tax" || orders.Columns[1].Identity != "by_default" {
		t.Fatal("normalized identity/comments differ from fixture")
	}
	for i, name := range []string{"tenant_id", "id", "customer_id", "amount", "total"} {
		if orders.Columns[i].Name != name || orders.Columns[i].Ordinal != i+1 {
			t.Fatal("column ordinal/name not preserved")
		}
	}
	foundPrimary, foundIncluded := false, false
	for _, constraint := range orders.Constraints {
		if constraint.Kind == "primary_key" && strings.Join(constraint.Columns, ",") == "tenant_id,id" {
			foundPrimary = true
		}
	}
	for _, index := range orders.Indexes {
		if index.Name == "orders_amount_idx" && strings.Join(index.IncludedColumns, ",") == "customer_id" && strings.Contains(index.Definition, "amount DESC") && index.Predicate != nil {
			foundIncluded = true
		}
	}
	if !foundPrimary || !foundIncluded {
		t.Fatal("composite primary key or included/predicate index missing")
	}
	before := snapshot.Stats.Estimates
	_, err = target.Exec(ctx, `INSERT INTO shop.customers(tenant_id,email) VALUES(1,'synthetic@example.test');INSERT INTO shop.orders(tenant_id,customer_id,amount) VALUES(1,1,12);ANALYZE shop.orders`)
	if err != nil {
		t.Fatal(err)
	}
	again, err := s.Run(ctx, alice, id, true)
	if err != nil || !again.Success || again.CreatedSnapshot {
		t.Fatal("statistics-only sync created snapshot", err, again.Code)
	}
	updated, err := s.Snapshot(ctx, alice, id, uuid.Nil)
	if err != nil {
		t.Fatal(err)
	}
	a, _ := json.Marshal(before)
	b, _ := json.Marshal(updated.Stats.Estimates)
	if updated.ID != snapshot.ID || updated.ContentHash != snapshot.ContentHash || string(a) == string(b) || !updated.Stats.ObservedAt.After(snapshot.Stats.ObservedAt) {
		t.Fatal("latest statistics not refreshed")
	}
	for _, change := range []string{`ALTER TABLE shop.orders ADD COLUMN reference text`, `ALTER TABLE shop.orders ADD CONSTRAINT reference_check CHECK(reference IS NULL OR length(reference)>0)`, `COMMENT ON TABLE shop.orders IS 'Changed comment'`} {
		if _, err := target.Exec(ctx, change); err != nil {
			t.Fatal(err)
		}
		result, err := s.Run(ctx, alice, id, true)
		if err != nil || !result.Success || !result.CreatedSnapshot {
			t.Fatal("structural change did not create snapshot", err, result.Code)
		}
	}
	page, err := s.Snapshots(ctx, alice, id, uuid.Nil, 2)
	if err != nil || len(page.Snapshots) != 2 || page.NextBefore == nil {
		t.Fatal("snapshot pagination failed")
	}
	next, err := s.Snapshots(ctx, alice, id, *page.NextBefore, 2)
	if err != nil || len(next.Snapshots) != 2 || next.Snapshots[0].ID == page.Snapshots[1].ID {
		t.Fatal("snapshot cursor duplicated rows")
	}
	if err := repo.DeleteUnit(ctx, alice, unit); !errors.Is(err, rbac.ErrNotEmpty) {
		t.Fatal("unit with connections deleted")
	}
	var audit string
	if err := db.QueryRow(`SELECT coalesce(json_agg(details)::text,'') FROM audit_log`).Scan(&audit); err != nil {
		t.Fatal(err)
	}
	output, _ := json.Marshal(logs.All())
	apiJSON, _ := json.Marshal(created)
	history, _ := json.Marshal(updated)
	for _, value := range []string{audit, string(output), string(apiJSON), string(history)} {
		if password != "" && strings.Contains(value, password) {
			t.Fatal("target secret leaked")
		}
	}
}
